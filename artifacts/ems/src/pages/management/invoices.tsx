import { useState } from "react";
import { useQueryClient } from "@tanstack/react-query";
import {
  useListInvoices,
  useCreateInvoice,
  useUpdateInvoiceStatus,
  useSendInvoiceReceipt,
  getListInvoicesQueryKey,
  useGetCurrentSession,
  Invoice,
} from "@workspace/api-client-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Textarea } from "@/components/ui/textarea";
import { Badge } from "@/components/ui/badge";
import { Card, CardContent } from "@/components/ui/card";
import { Label } from "@/components/ui/label";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogFooter,
} from "@/components/ui/dialog";
import { Skeleton } from "@/components/ui/skeleton";
import { Printer, Plus, Mail, Download, Share2 } from "lucide-react";
import { toast } from "sonner";
import { jsPDF } from "jspdf";

function downloadInvoicePdf(invoice: Invoice, companyName: string) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 48;
  const right = pageWidth - margin;
  let y = 64;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text(companyName, margin, y);
  doc.setFontSize(12);
  doc.text(invoice.invoiceNumber, right, y, { align: "right" });
  y += 18;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(110);
  doc.text(invoice.status === "paid" ? "RECEIPT / PAID INVOICE" : "INVOICE", margin, y);
  doc.text(`Issued ${invoice.createdAt.slice(0, 10)}`, right, y, { align: "right" });
  y += 14;
  if (invoice.paidAt) {
    doc.text(`Paid ${invoice.paidAt.slice(0, 10)}`, right, y, { align: "right" });
    y += 14;
  }

  y += 16;
  doc.setDrawColor(200);
  doc.line(margin, y, right, y);
  y += 24;

  doc.setTextColor(110);
  doc.text("Billed to", margin, y);
  y += 14;
  doc.setTextColor(20);
  doc.setFont("helvetica", "bold");
  doc.text(invoice.clientName, margin, y);
  doc.setFont("helvetica", "normal");
  y += 14;
  doc.setFontSize(9);
  doc.setTextColor(110);
  if (invoice.clientEmail) {
    doc.text(invoice.clientEmail, margin, y);
    y += 12;
  }
  if (invoice.clientPhone) {
    doc.text(invoice.clientPhone, margin, y);
    y += 12;
  }

  y += 20;
  doc.setFontSize(10);
  doc.setTextColor(110);
  doc.text("Description", margin, y);
  doc.text("Amount", right, y, { align: "right" });
  y += 8;
  doc.line(margin, y, right, y);
  y += 18;
  doc.setTextColor(20);
  const descLines = doc.splitTextToSize(invoice.description, right - margin - 120);
  doc.text(descLines, margin, y);
  doc.setFont("helvetica", "bold");
  doc.text(invoice.amount, right, y, { align: "right" });
  doc.setFont("helvetica", "normal");
  y += descLines.length * 13 + 12;
  doc.line(margin, y, right, y);
  y += 20;
  doc.setFont("helvetica", "bold");
  doc.text("Total", margin, y);
  doc.text(invoice.amount, right, y, { align: "right" });
  doc.setFont("helvetica", "normal");

  if (invoice.statusNote) {
    y += 28;
    doc.setFontSize(9);
    doc.setTextColor(110);
    doc.text("Note", margin, y);
    y += 12;
    doc.setTextColor(20);
    doc.text(doc.splitTextToSize(invoice.statusNote, right - margin), margin, y);
  }

  doc.setFontSize(8);
  doc.setTextColor(150);
  doc.text(
    `Generated by ${companyName}`,
    margin,
    doc.internal.pageSize.getHeight() - 40,
  );

  doc.save(`${invoice.invoiceNumber}.pdf`);
}

const FILTERS = ["all", "unpaid", "paid", "cancelled"] as const;
type Filter = (typeof FILTERS)[number];

function statusBadge(status: string) {
  const map: Record<string, string> = {
    paid: "bg-emerald-50 text-emerald-700 border-emerald-200",
    cancelled: "bg-red-50 text-red-700 border-red-200",
    unpaid: "bg-amber-50 text-amber-700 border-amber-200",
  };
  return (
    <Badge variant="outline" className={`capitalize ${map[status] || map.unpaid}`}>
      {status}
    </Badge>
  );
}

const EMPTY_FORM = {
  clientName: "",
  clientEmail: "",
  clientPhone: "",
  description: "",
  amount: "",
};

export default function InvoicesPage() {
  const queryClient = useQueryClient();
  const { data: invoices, isLoading } = useListInvoices();
  const createInvoice = useCreateInvoice();
  const updateStatus = useUpdateInvoiceStatus();
  const sendReceipt = useSendInvoiceReceipt();
  const { data: session } = useGetCurrentSession();

  const [filter, setFilter] = useState<Filter>("all");
  const [createOpen, setCreateOpen] = useState(false);
  const [form, setForm] = useState(EMPTY_FORM);
  const [detail, setDetail] = useState<Invoice | null>(null);
  const [statusTarget, setStatusTarget] = useState<{
    invoice: Invoice;
    action: "paid" | "cancelled";
  } | null>(null);
  const [statusNote, setStatusNote] = useState("");

  const filtered = invoices?.filter((i) => filter === "all" || i.status === filter) ?? [];

  const counts = {
    unpaid: invoices?.filter((i) => i.status === "unpaid").length ?? 0,
    paid: invoices?.filter((i) => i.status === "paid").length ?? 0,
    cancelled: invoices?.filter((i) => i.status === "cancelled").length ?? 0,
  };

  const invalidate = () =>
    queryClient.invalidateQueries({ queryKey: getListInvoicesQueryKey() });

  const submitCreate = () => {
    if (!form.clientName.trim() || !form.description.trim() || !form.amount.trim()) {
      toast.error("Client name, description, and amount are required.");
      return;
    }
    createInvoice.mutate(
      {
        data: {
          clientName: form.clientName.trim(),
          clientEmail: form.clientEmail.trim() || undefined,
          clientPhone: form.clientPhone.trim() || undefined,
          description: form.description.trim(),
          amount: form.amount.trim(),
        },
      },
      {
        onSuccess: (inv) => {
          invalidate();
          toast.success(`Invoice ${inv.invoiceNumber} created`);
          setCreateOpen(false);
          setForm(EMPTY_FORM);
          setDetail(inv);
        },
        onError: (error) => {
          toast.error("Failed to create invoice", {
            description: error.data?.error || "Unknown error occurred",
          });
        },
      },
    );
  };

  const submitStatus = () => {
    if (!statusTarget) return;
    updateStatus.mutate(
      {
        id: statusTarget.invoice.id,
        data: { status: statusTarget.action, note: statusNote.trim() || undefined },
      },
      {
        onSuccess: (inv) => {
          invalidate();
          toast.success(
            statusTarget.action === "paid"
              ? "Invoice marked as paid"
              : "Invoice cancelled",
          );
          setStatusTarget(null);
          setDetail((d) => (d && d.id === inv.id ? inv : d));
        },
        onError: (error) => {
          toast.error("Failed to update invoice", {
            description: error.data?.error || "Unknown error occurred",
          });
        },
      },
    );
  };

  const recordReceiptShared = (invoice: Invoice) => {
    sendReceipt.mutate(
      { id: invoice.id },
      {
        onSuccess: (inv) => {
          invalidate();
          setDetail((d) => (d && d.id === inv.id ? inv : d));
        },
      },
    );
  };

  const shareReceipt = async (invoice: Invoice) => {
    const companyName = session?.company.name || "5th Element";
    const paidDate = invoice.paidAt ? invoice.paidAt.slice(0, 10) : "";
    const text = [
      `Payment Receipt — ${invoice.invoiceNumber}`,
      `From: ${companyName}`,
      `To: ${invoice.clientName}`,
      ``,
      `Description: ${invoice.description}`,
      `Amount paid: ${invoice.amount}`,
      paidDate ? `Payment date: ${paidDate}` : "",
      ``,
      `Thank you for your payment!`,
    ]
      .filter((line, i, arr) => line !== "" || arr[i - 1] !== "")
      .join("\n");

    if (navigator.share) {
      try {
        await navigator.share({ title: `Receipt ${invoice.invoiceNumber}`, text });
        recordReceiptShared(invoice);
        toast.success("Receipt shared");
      } catch {
        // user closed the share sheet — not an error
      }
    } else {
      try {
        await navigator.clipboard.writeText(text);
        recordReceiptShared(invoice);
        toast.success("Receipt copied", {
          description: "Paste it into WhatsApp, SMS, or any messaging app.",
        });
      } catch {
        toast.error("Could not copy the receipt. Try the Download PDF option instead.");
      }
    }
  };

  return (
    <div className="p-6 space-y-6">
      <style>{`
        @media print {
          body * { visibility: hidden !important; }
          #invoice-print-area, #invoice-print-area * { visibility: visible !important; }
          #invoice-print-area {
            position: fixed; inset: 0; background: white; padding: 40px;
            z-index: 9999; overflow: visible; max-height: none !important;
          }
        }
      `}</style>

      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h1 className="text-3xl font-bold tracking-tight">Invoices</h1>
          <p className="text-muted-foreground mt-1">
            Bill your clients, track payments, and send receipts.
          </p>
        </div>
        <Button
          onClick={() => {
            setForm(EMPTY_FORM);
            setCreateOpen(true);
          }}
        >
          <Plus className="h-4 w-4 mr-1" /> Generate Invoice
        </Button>
      </div>

      <div className="grid grid-cols-3 gap-3 max-w-md">
        <Card>
          <CardContent className="p-4">
            <p className="text-2xl font-bold text-amber-600">{counts.unpaid}</p>
            <p className="text-xs text-muted-foreground">Unpaid</p>
          </CardContent>
        </Card>
        <Card>
          <CardContent className="p-4">
            <p className="text-2xl font-bold text-emerald-600">{counts.paid}</p>
            <p className="text-xs text-muted-foreground">Paid</p>
          </CardContent>
        </Card>
        <Card>
          <CardContent className="p-4">
            <p className="text-2xl font-bold text-red-600">{counts.cancelled}</p>
            <p className="text-xs text-muted-foreground">Cancelled</p>
          </CardContent>
        </Card>
      </div>

      <div className="flex gap-2">
        {FILTERS.map((f) => (
          <Button
            key={f}
            variant={filter === f ? "default" : "outline"}
            size="sm"
            className="capitalize"
            onClick={() => setFilter(f)}
          >
            {f}
          </Button>
        ))}
      </div>

      <Card>
        <CardContent className="p-0">
          {isLoading ? (
            <div className="p-6 space-y-2">
              {[1, 2, 3].map((i) => (
                <Skeleton key={i} className="h-10 w-full" />
              ))}
            </div>
          ) : (
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>Invoice #</TableHead>
                  <TableHead>Client</TableHead>
                  <TableHead>Amount</TableHead>
                  <TableHead>Description</TableHead>
                  <TableHead>Status</TableHead>
                  <TableHead className="text-right">Actions</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {filtered.length > 0 ? (
                  filtered.map((inv) => (
                    <TableRow
                      key={inv.id}
                      className="cursor-pointer"
                      tabIndex={0}
                      aria-label={`View invoice ${inv.invoiceNumber}`}
                      onClick={() => setDetail(inv)}
                      onKeyDown={(e) => {
                        if (e.key === "Enter" || e.key === " ") {
                          e.preventDefault();
                          setDetail(inv);
                        }
                      }}
                    >
                      <TableCell className="font-medium">{inv.invoiceNumber}</TableCell>
                      <TableCell>{inv.clientName}</TableCell>
                      <TableCell>{inv.amount}</TableCell>
                      <TableCell className="max-w-[180px] truncate">
                        {inv.description}
                      </TableCell>
                      <TableCell>
                        <div className="flex items-center gap-1.5">
                          {statusBadge(inv.status)}
                          {inv.receiptSentAt && (
                            <span title="Receipt sent">
                              <Mail className="h-3.5 w-3.5 text-muted-foreground" />
                            </span>
                          )}
                        </div>
                      </TableCell>
                      <TableCell
                        className="text-right"
                        onClick={(e) => e.stopPropagation()}
                        onKeyDown={(e) => e.stopPropagation()}
                      >
                        {inv.status === "unpaid" ? (
                          <div className="flex gap-2 justify-end">
                            <Button
                              size="sm"
                              variant="outline"
                              onClick={() => {
                                setStatusTarget({ invoice: inv, action: "paid" });
                                setStatusNote("");
                              }}
                            >
                              Mark Paid
                            </Button>
                            <Button
                              size="sm"
                              variant="outline"
                              className="text-red-600 hover:text-red-700"
                              onClick={() => {
                                setStatusTarget({ invoice: inv, action: "cancelled" });
                                setStatusNote("");
                              }}
                            >
                              Cancel
                            </Button>
                          </div>
                        ) : inv.status === "paid" ? (
                          <Button
                            size="sm"
                            variant="outline"
                            onClick={() => shareReceipt(inv)}
                          >
                            <Share2 className="h-4 w-4 mr-1" />
                            {inv.receiptSentAt ? "Share Again" : "Share Receipt"}
                          </Button>
                        ) : (
                          <span className="text-muted-foreground text-sm">—</span>
                        )}
                      </TableCell>
                    </TableRow>
                  ))
                ) : (
                  <TableRow>
                    <TableCell colSpan={6} className="text-center text-muted-foreground py-8">
                      No invoices yet. Generate one for a client to get started.
                    </TableCell>
                  </TableRow>
                )}
              </TableBody>
            </Table>
          )}
        </CardContent>
      </Card>

      {/* Create invoice dialog */}
      <Dialog open={createOpen} onOpenChange={setCreateOpen}>
        <DialogContent className="sm:max-w-lg">
          <DialogHeader>
            <DialogTitle>Generate Invoice</DialogTitle>
          </DialogHeader>
          <div className="space-y-4 max-h-[60vh] overflow-y-auto pr-1">
            <div className="space-y-2">
              <Label htmlFor="inv-client">Client name *</Label>
              <Input
                id="inv-client"
                value={form.clientName}
                onChange={(e) => setForm({ ...form, clientName: e.target.value })}
                placeholder="e.g. Acme Ltd"
              />
            </div>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              <div className="space-y-2">
                <Label htmlFor="inv-email">Client email</Label>
                <Input
                  id="inv-email"
                  type="email"
                  value={form.clientEmail}
                  onChange={(e) => setForm({ ...form, clientEmail: e.target.value })}
                  placeholder="For sending receipts"
                />
              </div>
              <div className="space-y-2">
                <Label htmlFor="inv-phone">Client phone</Label>
                <Input
                  id="inv-phone"
                  value={form.clientPhone}
                  onChange={(e) => setForm({ ...form, clientPhone: e.target.value })}
                  placeholder="Optional"
                />
              </div>
            </div>
            <div className="space-y-2">
              <Label htmlFor="inv-desc">Description *</Label>
              <Textarea
                id="inv-desc"
                value={form.description}
                onChange={(e) => setForm({ ...form, description: e.target.value })}
                placeholder="What is this invoice for? e.g. Website design — March"
                className="resize-none"
              />
            </div>
            <div className="space-y-2">
              <Label htmlFor="inv-amount">Amount *</Label>
              <Input
                id="inv-amount"
                value={form.amount}
                onChange={(e) => setForm({ ...form, amount: e.target.value })}
                placeholder="e.g. GHS 5,000"
              />
            </div>
          </div>
          <DialogFooter>
            <Button variant="outline" onClick={() => setCreateOpen(false)}>
              Cancel
            </Button>
            <Button onClick={submitCreate} disabled={createInvoice.isPending}>
              Generate Invoice
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>

      {/* Detail / print dialog */}
      <Dialog open={!!detail} onOpenChange={(o) => !o && setDetail(null)}>
        <DialogContent className="sm:max-w-xl">
          <DialogHeader>
            <DialogTitle>Invoice {detail?.invoiceNumber}</DialogTitle>
          </DialogHeader>
          {detail && (
            <div id="invoice-print-area" className="space-y-5 max-h-[60vh] overflow-y-auto">
              <div className="flex items-start justify-between">
                <div>
                  <p className="text-lg font-bold">{session?.company.name || "5th Element"}</p>
                  <p className="text-xs text-muted-foreground">Invoice</p>
                </div>
                <div className="text-right">
                  <p className="font-semibold">{detail.invoiceNumber}</p>
                  <p className="text-xs text-muted-foreground">
                    Issued {detail.createdAt.slice(0, 10)}
                  </p>
                  <div className="mt-1 flex justify-end">{statusBadge(detail.status)}</div>
                </div>
              </div>
              <div className="grid grid-cols-2 gap-3 text-sm border-t pt-4">
                <div>
                  <p className="text-muted-foreground">Billed to</p>
                  <p className="font-medium">{detail.clientName}</p>
                  {detail.clientEmail && (
                    <p className="text-xs text-muted-foreground">{detail.clientEmail}</p>
                  )}
                  {detail.clientPhone && (
                    <p className="text-xs text-muted-foreground">{detail.clientPhone}</p>
                  )}
                </div>
                {detail.paidAt && (
                  <div>
                    <p className="text-muted-foreground">Paid on</p>
                    <p className="font-medium">{detail.paidAt.slice(0, 10)}</p>
                  </div>
                )}
              </div>
              <div className="border rounded-md">
                <div className="flex justify-between items-start gap-4 p-3 border-b bg-muted/40 text-xs font-medium text-muted-foreground">
                  <span>Description</span>
                  <span>Amount</span>
                </div>
                <div className="flex justify-between items-start gap-4 p-3 text-sm">
                  <p className="whitespace-pre-wrap break-words min-w-0">
                    {detail.description}
                  </p>
                  <p className="font-semibold whitespace-nowrap">{detail.amount}</p>
                </div>
                <div className="flex justify-between items-center gap-4 p-3 border-t text-sm">
                  <span className="font-medium">Total</span>
                  <span className="font-bold">{detail.amount}</span>
                </div>
              </div>
              {detail.statusNote && (
                <div>
                  <p className="text-sm text-muted-foreground mb-1">Note</p>
                  <p className="text-sm whitespace-pre-wrap break-words">{detail.statusNote}</p>
                </div>
              )}
              {detail.receiptSentAt && (
                <p className="text-xs text-muted-foreground">
                  Receipt sent {detail.receiptSentAt.slice(0, 10)}
                </p>
              )}
            </div>
          )}
          <DialogFooter className="flex-wrap gap-2">
            <Button variant="outline" onClick={() => window.print()}>
              <Printer className="h-4 w-4 mr-1" /> Print
            </Button>
            <Button
              variant="outline"
              onClick={() =>
                detail &&
                downloadInvoicePdf(detail, session?.company.name || "5th Element")
              }
            >
              <Download className="h-4 w-4 mr-1" /> Download PDF
            </Button>
            {detail?.status === "unpaid" && (
              <>
                <Button
                  variant="outline"
                  className="text-red-600 hover:text-red-700"
                  onClick={() => {
                    setStatusTarget({ invoice: detail, action: "cancelled" });
                    setStatusNote("");
                  }}
                >
                  Cancel Invoice
                </Button>
                <Button
                  onClick={() => {
                    setStatusTarget({ invoice: detail, action: "paid" });
                    setStatusNote("");
                  }}
                >
                  Mark Paid
                </Button>
              </>
            )}
            {detail?.status === "paid" && (
              <Button onClick={() => shareReceipt(detail)}>
                <Share2 className="h-4 w-4 mr-1" />
                {detail.receiptSentAt ? "Share Again" : "Share Receipt"}
              </Button>
            )}
          </DialogFooter>
        </DialogContent>
      </Dialog>

      {/* Status confirmation dialog */}
      <Dialog open={!!statusTarget} onOpenChange={(o) => !o && setStatusTarget(null)}>
        <DialogContent>
          <DialogHeader>
            <DialogTitle>
              {statusTarget?.action === "paid" ? "Mark Invoice as Paid" : "Cancel Invoice"}
            </DialogTitle>
          </DialogHeader>
          <div className="space-y-2">
            <Label htmlFor="invoice-status-note">Note (optional)</Label>
            <Textarea
              id="invoice-status-note"
              value={statusNote}
              onChange={(e) => setStatusNote(e.target.value)}
              placeholder={
                statusTarget?.action === "paid"
                  ? "e.g. Paid via bank transfer on..."
                  : "Reason for cancelling this invoice..."
              }
              className="resize-none"
            />
          </div>
          <DialogFooter>
            <Button variant="outline" onClick={() => setStatusTarget(null)}>
              Back
            </Button>
            <Button onClick={submitStatus} disabled={updateStatus.isPending}>
              Confirm
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </div>
  );
}
